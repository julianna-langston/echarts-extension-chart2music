const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const fixturePath = path.join(root, "stories", "chart-examples.ts");
const outputDirectory = path.join(root, "stories", "generated");

const fixtureSource = fs
  .readFileSync(fixturePath, "utf8")
  .replace(/export type DemoExample = \{[\s\S]*?\};\s*/, "")
  .replaceAll("export const ", "const ");

const { optionsByType, supportedByChart2Music } = Function(
  `${fixtureSource}\nreturn { optionsByType, supportedByChart2Music };`
)();

const sectionFor = (example) => {
  if (!supportedByChart2Music.has(example.type)) {
    return "Visual only";
  }
  if (["sunburst", "tree", "treemap"].includes(example.type)) {
    return "Hierarchy";
  }
  if (example.type === "effectScatter") {
    return "Scatter";
  }
  return example.type[0].toUpperCase() + example.type.slice(1);
};

const identifierFor = (title, index, used) => {
  const base = title
    .replace(/[^a-zA-Z0-9]+(.)?/g, (_match, letter) => (letter ? letter.toUpperCase() : ""))
    .replace(/^\d/, "Example$&") || `Example${index + 1}`;
  const identifier = /^[A-Z]/.test(base) ? base : base[0].toUpperCase() + base.slice(1);
  const unique = used.has(identifier) ? `${identifier}${index + 1}` : identifier;
  used.add(unique);
  return unique;
};

const groups = new Map();
optionsByType.forEach((example) => {
  const section = sectionFor(example);
  const examples = groups.get(section) ?? [];
  examples.push(example);
  groups.set(section, examples);
});

fs.rmSync(outputDirectory, { recursive: true, force: true });
fs.mkdirSync(outputDirectory, { recursive: true });

groups.forEach((examples, section) => {
  const used = new Set();
  const isVisualOnly = section === "Visual only";
  const exports = examples.map((example, index) => {
    const title = example.title ?? example.type;
    const identifier = identifierFor(title, index, used);
    return `export const ${identifier}: Story = { name: ${JSON.stringify(title)}, render: () => createEChartsExample(getExample(${JSON.stringify(title)}), ${!isVisualOnly}) };`;
  });
  const fileName = section.toLowerCase().replace(/[^a-z0-9]+/g, "-");
  const source = `// Generated by scripts/generate-storybook-stories.cjs.\nimport type { Meta, StoryObj } from "@storybook/html-vite";\nimport { optionsByType } from "../chart-examples.js";\nimport { createEChartsExample } from "../EChartsExample.js";\n\nconst getExample = (title: string) => {\n  const example = optionsByType.find((item) => (item.title ?? item.type) === title);\n  if (!example) {\n    throw new Error(\`Missing Storybook example: \${title}\`);\n  }\n  return example;\n};\n\nconst meta = { title: "ECharts Examples/${section}" } satisfies Meta;\nexport default meta;\ntype Story = StoryObj;\n\n${exports.join("\n")}\n`;
  fs.writeFileSync(path.join(outputDirectory, `${fileName}.stories.ts`), source);
});

console.log(`Generated ${optionsByType.length} Storybook stories in ${groups.size} sections.`);
